#!/usr/bin/env node
// Rebuilds seed/assets/credits.json from every asset list in seed/assets (world photos and real-object photos).
// Each entry carries licence, attribution and alt text in both languages. Usage: node tools/assets/credits.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SEED = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'seed', 'assets');
const skip = new Set(['picks.json', 'rejected.json', 'credits.json', 'manifest.json', 'vocab.json', 'sprites.json']);
const photos = [];
for (const f of fs.readdirSync(SEED).filter((x) => x.endsWith('.json') && !skip.has(x)).sort()) {
  for (const a of JSON.parse(fs.readFileSync(path.join(SEED, f), 'utf8'))) {
    const v = [...(a.variants ?? [])].sort((x, y) => x.w - y.w)[0];
    photos.push({
      id: a.id, world: a.world_id ?? 'all', role: a.role ?? a.kind, thumb: v?.file ?? '',
      alt_fr: a.alt_fr, alt_en: a.alt_en,
      attribution_text: a.attribution_text, creator: a.creator, creator_url: a.creator_url ?? null,
      source_name: a.source_name, source_url: a.source_url, licence: a.licence, licence_url: a.licence_url,
    });
  }
}
const missing = photos.filter((p) => !p.alt_fr || !p.alt_en || !p.licence || !p.attribution_text);
if (missing.length) { console.error('incomplete credits:', missing.map((m) => m.id).join(', ')); process.exit(1); }
fs.writeFileSync(path.join(SEED, 'credits.json'), JSON.stringify({ _note: 'Data for the in-app credits page and GET /v1/credits. Generated by tools/assets/credits.mjs.', photos, groups: [] }, null, 1) + '\n');
console.log('credits', photos.length);

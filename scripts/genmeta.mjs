// Generates Go code from the contract that oapi-codegen does not produce:
//   internal/httpapi/opmeta_gen.go      Go operation name (as given to strict middleware) -> public flag + allowed roles (from `security: []` and `x-roles`)
//   internal/app/unimplemented_gen.go   a 501 stub for every operation of api.StrictServerInterface
// Run through scripts/gen.sh. Reads ../frontend/contracts/openapi.yaml.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
// FRONTEND_DIR overrides the sibling checkout (any worktree layout)
const FE = process.env.FRONTEND_DIR || '../frontend';
const pnpmDir = `${FE}/node_modules/.pnpm`;
const yamlPkg = readdirSync(pnpmDir).find((d) => d.startsWith('js-yaml@'));
const yaml = require(path.resolve(`${pnpmDir}/${yamlPkg}/node_modules/js-yaml`));
const spec = yaml.load(readFileSync(`${FE}/contracts/openapi.yaml`, 'utf8'));

const ops = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    if (!op || !op.operationId) continue;
    ops.push({
      id: op.operationId,
      go: op.operationId[0].toUpperCase() + op.operationId.slice(1), // oapi-codegen method name
      method: method.toUpperCase(),
      path,
      public: Array.isArray(op.security) && op.security.length === 0,
      roles: op['x-roles'] || [],
    });
  }
}
ops.sort((a, b) => a.id.localeCompare(b.id));

const meta = ops
  .map((o) => `\t"${o.go}": {Method: "${o.method}", Path: "${o.path}", Public: ${o.public}, Roles: []string{${o.roles.map((r) => `"${r}"`).join(', ')}}},`)
  .join('\n');
writeFileSync(
  'internal/httpapi/opmeta_gen.go',
  `// Code generated by scripts/genmeta.mjs from the OpenAPI contract. DO NOT EDIT.

package httpapi

// Ops maps each operation name to its contract metadata (Spring: the annotations @PreAuthorize / @PermitAll, as a table).
var Ops = map[string]OpMeta{
${meta}
}
`,
);

const stubs = ops
  .map(
    (o) => `// ${o.go} is not built yet: answers 501.
func (Unimplemented) ${o.go}(ctx context.Context, request api.${o.go}RequestObject) (api.${o.go}ResponseObject, error) {
\treturn nil, httpapi.ErrNotImplemented
}
`,
  )
  .join('\n');
writeFileSync(
  'internal/app/unimplemented_gen.go',
  `// Code generated by scripts/genmeta.mjs from the OpenAPI contract. DO NOT EDIT.

package app

import (
\t"context"

\t"github.com/Perrin-Nj/numerix-api/api"
\t"github.com/Perrin-Nj/numerix-api/internal/httpapi"
)

// Unimplemented satisfies api.StrictServerInterface with a 501 for every operation
// (Spring: an abstract adapter class). Server embeds it and overrides the operations it implements.
type Unimplemented struct{}

${stubs}`,
);
console.log(ops.length, 'operations');
